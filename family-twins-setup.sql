-- ============================================================
-- Единый вход для семьи близнецов Богдан: Давид (№2) + Ульяна (№3)
-- ============================================================
-- Как выполнить:
--   1. Открыть Supabase → проект → SQL Editor → New query.
--   2. Вставить весь этот файл и нажать Run.
--   3. Внизу появятся результаты проверочных запросов (см. комментарии).
-- Повторный запуск безопасен: все команды идемпотентны.
--
-- Что делает скрипт:
--   1. Отключает старый код входа Давида (№2, CZX-982) — семья теперь
--      входит по общему коду Ульяны (№3, UXG-435), выбрав любого ребёнка.
--   2. Переименовывает запись №3 в «Богдан Давид и Ульяна».
--   3. Переносит старые сообщения чата семьи Давида (№2) в общую ветку №3,
--      чтобы вся переписка семьи была в одном месте.
--   Заметки и напоминания (family_notes) НЕ трогаем — они остаются
--   раздельными по детям, приложение показывает семье оба набора.

-- 1. Удаляем старый код Давида — вход по CZX-982 больше не работает
delete from family_codes where family_n = 2;

-- 2. Общий код семьи: запись №3 подписываем на обоих детей
update family_codes
set child = 'Богдан Давид и Ульяна'
where family_n = 3;

-- 3. Старые сообщения чата семьи №2 переносим в общую ветку №3
update family_messages
set family_n = 3
where family_n = 2;

-- ============================================================
-- Проверка (результаты внизу после Run):
-- ============================================================

-- Должна остаться одна строка: №3, «Богдан Давид и Ульяна», код UXG-435.
-- Строки с family_n = 2 быть НЕ должно.
select * from family_codes where family_n in (2, 3) order by family_n;

-- Сообщений с family_n = 2 быть не должно (count = 0)
select count(*) as leftover_family2_messages
from family_messages where family_n = 2;

-- Сколько всего сообщений теперь в общей ветке семьи №3
select count(*) as family3_messages
from family_messages where family_n = 3;
