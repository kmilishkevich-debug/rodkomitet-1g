  'По итогам голосования едем 12 декабря в новогоднюю «Сказочную страну МалиВур».' || chr(10) ||
  chr(10) ||
  'Сумма с семьи: 142 BYN (ребёнок).' || chr(10) ||
  'Семьи, где едет мама: Белоус — 267, Милишкевич — 267, Шило — 267, Тылецкий — 284 (с обедом).' || chr(10) ||
  'Семья Богдан (двое детей) — 284.' || chr(10) ||
  chr(10) ||
  'До среды 18 ноября нужно сдать предоплату — минимум 20% от суммы семьи. Кто хочет, может сразу сдать всю сумму. Оставшуюся часть сдаём до 7 декабря. Своя сумма и остаток видны во вкладке «Деньги → Сборы».',
  true, false, false,
