-- ЧАСТЬ 1. СВОИ СУММЫ СЕМЕЙ -------------------------------------------------
-- amounts (jsonb) — суммы семей, у которых она отличается от общей:
--   ключ — № первой строки семьи (у близнецов — меньший номер),
--   значение — сумма. Пример: {"2": 284, "18": 267}.
-- NULL или нет ключа = семья сдаёт общую сумму (amount).

alter table fee_campaigns add column if not exists amounts jsonb;

-- ЧАСТЬ 2. СБОР «ЭКСКУРСИЯ В МАЛИВУР» ---------------------------------------
-- Едут 20 семей (21 ребёнок — у Богданов двое) + 4 мамы.
-- Ребёнок — 142; мама с обедом (Тылецкая) — 142; мамы без обеда
-- (Белоус, Милишкевич, Шило) — по 125. Итого 3 499 BYN.
-- До среды 18.11 — минимум 20% от суммы семьи (предоплата),
-- оставшуюся сумму — до 7 декабря. Дедлайн сбора ставим 07.12.

insert into fee_campaigns
  (title, amount, deadline, participants, amounts, teacher_visible, created_by, sort)
select
  'Экскурсия «МалиВур» 12 декабря',
  142,
  '2026-12-07',
  '[1,2,3,4,6,8,9,11,12,13,14,16,17,18,19,20,23,24,25,26,27]'::jsonb,
  '{"1": 267, "2": 284, "18": 267, "24": 284, "26": 267}'::jsonb,
  false,
  'Кристина',
  coalesce((select max(sort) from fee_campaigns), 0) + 1
where not exists (
  select 1 from fee_campaigns where title = 'Экскурсия «МалиВур» 12 декабря'
);

