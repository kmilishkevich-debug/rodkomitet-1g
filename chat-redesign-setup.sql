-- ============================================================
-- Наш 1 «Г» — новый чат с учителем (28.10.2026)
--
-- Что это: переработка личной переписки семьи и учителя —
-- стикеры «Наш пушистик», ответы на сообщения, честные статусы
-- «Отправлено/Прочитано» со временем и мягкое удаление
-- («Сообщение удалено» вместо исчезновения без следа).
--
-- Новые колонки family_messages:
--   read_at    — когда собеседник прочитал сообщение (открыл чат);
--                раньше была только галочка без времени.
--   sticker    — идентификатор стикера из набора приложения
--                (thanks, understood, good-day, see-you, hooray,
--                received); у обычного текста — null.
--   reply_to   — на какое сообщение это ответ (цитата).
--   deleted_at — когда сообщение удалили; текст при этом стирается,
--                в чате остаётся строка «Сообщение удалено».
--
-- Доставки «две серые галочки» в приложении нет и не появится от
-- этого файла: подтверждений от устройства получателя мы не собираем,
-- поэтому интерфейс честно показывает только «Отправлено» и
-- «Прочитано» (ТЗ п. 10).
--
-- Как запустить: Supabase → проект rodkomitet-1g → SQL Editor →
-- New query → вставить ВЕСЬ файл (Ctrl+A, Ctrl+C) → щёлкнуть в тексте,
-- чтобы снять выделение → Run. Повторный запуск безопасен.
-- ============================================================

alter table family_messages
  add column if not exists read_at    timestamptz,
  add column if not exists sticker    text,
  add column if not exists reply_to   uuid,
  add column if not exists deleted_at timestamptz;

-- Текст теперь может быть пустым: сообщение-стикер и удалённое
-- сообщение живут без текста
alter table family_messages alter column text drop not null;


-- ============================================================
-- ПРОВЕРКА: четыре строки с именами новых колонок
-- ============================================================
select column_name as "Колонка"
from information_schema.columns
where table_name = 'family_messages'
  and column_name in ('read_at', 'sticker', 'reply_to', 'deleted_at')
order by column_name;
