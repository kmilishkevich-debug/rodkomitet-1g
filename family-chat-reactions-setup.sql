-- ============================================================
-- Наш 1 «Г» — реакции на сообщения в переписке с семьёй (23.10.2026)
--
-- Что это: учитель и родитель могут поставить эмодзи-реакцию
-- (❤️ 👍 😊 …) на сообщение собеседника в личной переписке —
-- быстрый ответ без текста.
--
-- Как хранится: колонка reactions (jsonb) в family_messages.
-- У каждой стороны не больше одной реакции на сообщение:
--   {"teacher": "👍", "family": "❤️"}
-- Пустое значение (null) — реакций нет.
--
-- Как запустить: Supabase → проект rodkomitet-1g → SQL Editor →
-- New query → вставить ВЕСЬ файл → Run. Повторный запуск безопасен.
-- ============================================================

alter table family_messages
  add column if not exists reactions jsonb;


-- ============================================================
-- ПРОВЕРКА: должно вернуть одну строку «reactions | jsonb»
-- ============================================================
select column_name as "Колонка", data_type as "Тип"
from information_schema.columns
where table_name = 'family_messages'
  and column_name = 'reactions';
