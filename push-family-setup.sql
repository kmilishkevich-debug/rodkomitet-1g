-- ===== Адресные пуши семье =====
-- Личное сообщение учителя семье должно уходить пушем ТОЛЬКО этой семье,
-- а не всем родителям. Для этого подписка устройства запоминает номер семьи.
-- Выполнить один раз в Supabase (SQL Editor). Безопасно повторять.

alter table public.push_subscriptions
  add column if not exists family_n int;

-- Примечание: колонка заполняется приложением автоматически при следующем
-- открытии приложения родителем (тихая синхронизация подписки). До этого
-- пуши о личных сообщениях просто никому не уйдут — текст переписки
-- в любом случае больше не рассылается всем.
