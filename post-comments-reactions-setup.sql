-- ============================================================
-- Наш 1 «Г» — реакции в обсуждениях под публикациями (23.10.2026)
--
-- Что это: учитель и семьи могут поставить эмодзи-реакцию
-- (❤️ 👍 😊 …) на сообщение в общем обсуждении под объявлением,
-- заданием или событием — быстрый ответ без текста.
--
-- Как хранится: колонка reactions (jsonb) в post_comments.
-- У каждого участника не больше одной реакции на сообщение,
-- ключ — кто поставил: "t" — учитель, "f18" — семья №18:
--   {"t": "👍", "f18": "❤️", "f14": "❤️"}
-- Пустое значение (null) — реакций нет.
--
-- Как запустить: Supabase → проект rodkomitet-1g → SQL Editor →
-- New query → вставить ВЕСЬ файл → Run. Повторный запуск безопасен.
-- ============================================================

alter table post_comments
  add column if not exists reactions jsonb;


-- ============================================================
-- ПРОВЕРКА: должно вернуть одну строку «reactions | jsonb»
-- ============================================================
select column_name as "Колонка", data_type as "Тип"
from information_schema.columns
where table_name = 'post_comments'
  and column_name = 'reactions';
