-- ===== ЧАСТЬ 1. Таблица семей =====
create table if not exists families (
  n          int primary key,             -- номер в списке класса
  child      text not null,               -- «Фамилия Имя» ребёнка
  father     text not null default '',    -- ФИО папы
  mother     text not null default '',    -- ФИО мамы
  phone1     text not null default '',    -- телефон папы
  phone2     text not null default '',    -- телефон мамы
  note       text not null default '',    -- заметка («Родительский комитет» и т.п.)
  hidden     boolean not null default false, -- true — ребёнок выбыл (скрыт, не удалён)
  twin_with  int,                         -- для близнецов: номер «главной» строки семьи
  updated_at timestamptz not null default now()
);

alter table families enable row level security;
drop policy if exists "families read" on families;
create policy "families read" on families for select using (true);
drop policy if exists "families write" on families;
create policy "families write" on families for all to authenticated using (true) with check (true);

-- ===== ЧАСТЬ 2. Журнал правок =====
create table if not exists family_edits_log (
  id        uuid primary key default gen_random_uuid(),
  n         int,               -- номер семьи
  child     text not null,     -- ребёнок, к которому относится правка
  field     text not null,     -- что меняли: ребёнок / папа / мама / телефон / заметка / скрыт …
  old_value text not null default '',
  new_value text not null default '',
  editor    text not null default 'Комитет',
  at        timestamptz not null default now()
);

alter table family_edits_log enable row level security;
drop policy if exists "family_edits_log read" on family_edits_log;
create policy "family_edits_log read" on family_edits_log for select using (true);
drop policy if exists "family_edits_log write" on family_edits_log;
create policy "family_edits_log write" on family_edits_log for all to authenticated using (true) with check (true);

