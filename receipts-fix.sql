-- ПОЧИНКА ЗАГРУЗКИ ЧЕКОВ РОДИТЕЛЯМИ (октябрь 2026)
--
-- Что было не так: правило хранилища чеков разрешало сохранять файлы только
-- вошедшим с логином-паролем (комитет и учитель). Родители входят по семейному
-- коду без аккаунта в базе, поэтому база отклоняла их чеки — отсюда ошибка
-- после кнопки «Отправить».
--
-- Что делаем: разрешаем сохранять чеки всем пользователям приложения.
-- Это безопасно в рамках класса: адрес приложения знают только семьи,
-- фото сжимаются в телефоне до ~1 МБ, а менять и удалять уже загруженные
-- чеки по-прежнему могут только комитет и учитель.
--
-- Запустить один раз в Supabase → SQL Editor → Run. Заработает сразу.

drop policy if exists "receipts write" on storage.objects;
create policy "receipts write" on storage.objects
  for insert with check (bucket_id = 'receipts');
